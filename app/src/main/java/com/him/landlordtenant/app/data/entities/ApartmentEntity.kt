    val garbageCollectionAvailable: Boolean,
    val internetAvailable: Boolean,
    val gasAvailable: Boolean,
    val boreholeAvailable: Boolean,
    val backupWater: Boolean,
    val backupElectricity: Boolean,
    val waterProvider: String?,
    val electricityProvider: String?,
    val availableHouseTypes: List<HouseType>,
    val minimumRent: Double,
    val maximumRent: Double,
    val contactPhone: String,
    val contactEmail: String,
    val whatsappNumber: String?,
    val rules: List<String>,
    val defaultAgreementId: String?,
    val agreementRequired: Boolean,
    val verificationStatus: VerificationStatus,
    val verifiedAt: String?,
    val verifiedBy: String?,
    val listingStatus: ApartmentListingStatus,
    val isPublished: Boolean,
    val isFeatured: Boolean,
    val viewsCount: Long,
    val inquiriesCount: Long,
    val applicationsCount: Long,
    val rating: Double,
    val reviewCount: Int,
    val caretakerName: String?,
    val caretakerPhone: String?,
    val createdAt: String?,
    val updatedAt: String?,
    val createdBy: String?,
    val updatedBy: String?
)

