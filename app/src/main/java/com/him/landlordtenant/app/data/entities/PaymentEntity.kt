package com.him.landlordtenant.app.data.entities

import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.PrimaryKey
import com.him.landlordtenant.app.enums.PaymentMethod
import com.him.landlordtenant.app.data.model.*

@Entity(tableName = "payments")
data class PaymentEntity(
    @PrimaryKey val id: String,
    val paymentReference: String,
    val transactionReference: String?,
    val providerTransactionId: String?,
    val tenantId: String?,
    val landlordId: String,
    val apartmentId: String,
    val houseId: String,
    val billId: String?,
    val billNumber: String?,
    val amount: Double,
    val currency: String,
    val paymentType: PaymentType,
    val paymentMethod: PaymentMethod,
    val provider: PaymentProvider,
    val payerName: String?,
    val payerPhoneNumber: String?,
    val payerEmail: String?,
    @Embedded(prefix = "dest_") val destination: PaymentDestination?,
    val status: PaymentStatus,
    val providerResponseCode: String?,
    val providerResponseMessage: String?,
    val providerReceiptNumber: String?,
    val initiatedAt: String?,
    val processingAt: String?,
    val completedAt: String?,
    val failedAt: String?,
    val cancelledAt: String?,
    val failureReason: String?,
    val failureCode: String?,
    val verificationStatus: PaymentVerificationStatus,
    val verifiedAt: String?,
    val receiptId: String?,
    @Embedded(prefix = "refund_") val refund: RefundInformation?,
    val description: String?,
    val notes: String?,
    val auditEvents: List<PaymentAuditEvent>,
    val createdAt: String?,
    val updatedAt: String?
)

