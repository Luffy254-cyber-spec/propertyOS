package com.him.landlordtenant.app.data.entities

import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.PrimaryKey
import com.him.landlordtenant.app.data.model.*

@Entity(tableName = "tenants")
data class TenantEntity(
    @PrimaryKey val id: String,
    val userId: String,
    val occupation: String?,
    val employer: String?,
    val nationality: String?,
    val idType: TenantIdType,
    val idNumber: String?,
    val idDocumentUrl: String?,
    val verificationStatus: IdentityVerificationStatus,
    val verificationSubmittedAt: String?,
    val verificationCompletedAt: String?,
    val verificationNotes: String?,
    val currentApartmentId: String?,
    val currentFloorId: String?,
    val currentHouseId: String?,
    val currentLandlordId: String?,
    val currentPropertyManagerId: String?,
    val tenancyStatus: TenancyStatus,
    val leaseId: String?,
    val leaseStartDate: String?,
    val leaseEndDate: String?,
    val moveInDate: String?,
    val expectedMoveOutDate: String?,
    val monthlyRent: Double,
    val securityDeposit: Double,
    val outstandingRent: Double,
    val outstandingBills: Double,
    val rentDueDay: Int,
    val gracePeriodDays: Int,
    val autoPaymentEnabled: Boolean,
    val numberOfOccupants: Int,
    val occupants: List<TenantOccupant>,
    @Embedded(prefix = "emergency_") val emergencyContact: TenantEmergencyContact?,
    val houseConditionAtMoveIn: HouseCondition,
    val moveInInspectionCompleted: Boolean,
    val agreementId: String?,
    val signedAgreementUrl: String?,
    val otherDocumentUrls: List<String>,
    val vacateRequestId: String?,
    val vacateRequestedAt: String?,
    val vacateNoticeDays: Int,
    val tenantGroupChatId: String?,
    val totalRentPaid: Double,
    val totalBillsPaid: Double,
    val totalPayments: Int,
    val previousTenancies: List<PreviousTenancy>,
    val createdAt: String?,
    val updatedAt: String?
)

