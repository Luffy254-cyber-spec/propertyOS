package com.him.landlordtenant.app.data.entities

import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.PrimaryKey
import com.him.landlordtenant.app.data.model.*

@Entity(tableName = "houses")
data class HouseEntity(
    @PrimaryKey val id: String,
    val apartmentId: String,
    val floorId: String,
    val houseNumber: String,
    val houseType: HouseType,
    val bedrooms: Int,
    val bathrooms: Int,
    val sizeSquareMeters: Double,
    val description: String,
    val monthlyRent: Double,
    val securityDeposit: Double,
    val serviceCharge: Double,
    val waterBill: Double,
    val electricityBill: Double,
    val garbageBill: Double,
    val internetBill: Double,
    val otherMonthlyCharges: Double,
    @Embedded(prefix = "billing_") val billingConfiguration: BillingConfiguration,
    val status: HouseStatus,
    val tenantId: String?,
    val tenantName: String?,
    val condition: HouseCondition,
    val conditionDescription: String,
    val availableFrom: String?,
    val expectedReadyDate: String?,
    val imageUrls: List<String>,
    val videoUrls: List<String>,
    val facilities: List<HouseFacility>,
    val latitude: Double?,
    val longitude: Double?,
    val moveInDate: String?,
    val leaseStartDate: String?,
    val leaseEndDate: String?,
    val rentDueDay: Int,
    val gracePeriodDays: Int,
    val houseRules: List<String>,
    val agreementId: String?,
    val activeMaintenanceRequestCount: Int,
    val isVerified: Boolean,
    val isListed: Boolean,
    val createdAt: String?,
    val updatedAt: String?,
    val createdBy: String?,
    val updatedBy: String?
)

