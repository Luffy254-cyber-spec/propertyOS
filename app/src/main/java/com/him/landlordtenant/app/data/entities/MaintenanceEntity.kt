package com.him.landlordtenant.app.data.entities

import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.PrimaryKey
import com.him.landlordtenant.app.data.model.*

@Entity(tableName = "maintenance_requests")
data class MaintenanceEntity(
    @PrimaryKey val id: String,
    val requestNumber: String,
    val apartmentId: String,
    val floorId: String?,
    val houseId: String,
    val houseNumber: String,
    val tenantId: String?,
    val tenantName: String?,
    val landlordId: String,
    val propertyManagerId: String?,
    val title: String,
    val description: String,
    val category: MaintenanceCategory,
    val priority: MaintenancePriority,
    val status: MaintenanceStatus,
    val attachments: List<MaintenanceAttachment>,
    @Embedded(prefix = "loc_") val location: MaintenanceLocation?,
    val assignedProfessionalId: String?,
    val assignedProfessionalName: String?,
    val assignedProfessionalPhone: String?,
    val estimatedCost: Double?,
    val approvedBudget: Double?,
    val actualCost: Double?,
    val currency: String,
    val preferredVisitDate: String?,
    val scheduledVisitDate: String?,
    val scheduledVisitTime: String?,
    val technicianNotes: String?,
    val landlordNotes: String?,
    val tenantNotes: String?,
    val completionDescription: String?,
    val completionAttachments: List<MaintenanceAttachment>,
    val completedAt: String?,
    val tenantConfirmedCompletion: Boolean,
    val tenantConfirmedAt: String?,
    val tenantRating: Int?,
    val tenantFeedback: String?,
    val isEmergency: Boolean,
    val createdAt: String?,
    val updatedAt: String?,
    val closedAt: String?,
    val syncStatus: SyncStatus = SyncStatus.SYNCED
)

