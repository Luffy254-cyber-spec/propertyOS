package com.him.landlordtenant.app.data.entities

import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.PrimaryKey
import com.him.landlordtenant.app.data.model.*

@Entity(tableName = "users")
data class UserEntity(
    @PrimaryKey val id: String,
    val firebaseUid: String?,
    val email: String?,
    val phoneNumber: String?,
    val firstName: String,
    val middleName: String?,
    val lastName: String,
    val displayName: String,
    val profileImageUrl: String?,
    val roles: List<UserRole>,
    val activeRole: UserRole,
    val authProvider: AuthProvider,
    val accountStatus: AccountStatus,
    val emailVerified: Boolean,
    val phoneVerified: Boolean,
    val identityVerificationStatus: IdentityVerificationStatus,
    val username: String?,
    val county: String?,
    val town: String?,
    val country: String,
    @Embedded(prefix = "pref_") val preferences: UserPreferences,
    @Embedded(prefix = "notif_") val notificationSettings: NotificationSettings,
    val twoFactorEnabled: Boolean,
    val lastLoginAt: String?,
    val lastLoginIp: String?,
    val loginCount: Long,
    val landlordProfileId: String?,
    val tenantProfileId: String?,
    val managedApartmentIds: List<String>,
    val createdAt: String?,
    val updatedAt: String?,
    val deletedAt: String?
)

fun User.toEntity() = UserEntity(
    id = id,
    firebaseUid = firebaseUid,
    email = email,
    phoneNumber = phoneNumber,
    firstName = firstName,
    middleName = middleName,
    lastName = lastName,
    displayName = displayName,
    profileImageUrl = profileImageUrl,
    roles = roles,
    activeRole = activeRole,
    authProvider = authProvider,
    accountStatus = accountStatus,
    emailVerified = emailVerified,
    phoneVerified = phoneVerified,
    identityVerificationStatus = identityVerificationStatus,
    username = username,
    county = county,
    town = town,
    country = country,
    preferences = preferences,
    notificationSettings = notificationSettings,
    twoFactorEnabled = twoFactorEnabled,
    lastLoginAt = lastLoginAt,
    lastLoginIp = lastLoginIp,
    loginCount = loginCount,
    landlordProfileId = landlordProfileId,
    tenantProfileId = tenantProfileId,
    managedApartmentIds = managedApartmentIds,
    createdAt = createdAt,
    updatedAt = updatedAt,
    deletedAt = deletedAt
)

